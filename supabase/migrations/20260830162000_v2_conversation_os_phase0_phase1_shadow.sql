-- Backup scheduler. Queue-insert triggers above are primary; cron drains retry/backlog jobs.
do $$
begin
  begin
    create extension if not exists pg_cron;
  exception when others then
    raise notice 'pg_cron unavailable; queue insert trigger remains active: %', sqlerrm;
  end;
end $$;

do $$
declare
  existing_job_id bigint;
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron')
     and exists (select 1 from pg_extension where extname = 'pg_net') then

    for existing_job_id in
      select jobid from cron.job
      where jobname in ('alameen-whatsapp-shadow-worker','alameen-whatsapp-v2-shadow-worker')
    loop
      perform cron.unschedule(existing_job_id);
    end loop;

    perform cron.schedule(
      'alameen-whatsapp-shadow-worker',
      '* * * * *',
      $cron$
      select net.http_post(
        url := 'https://www.ameenfinance.co/api/internal/whatsapp-shadow/worker',
        headers := jsonb_build_object(
          'Content-Type', 'application/json',
          'x-shadow-worker-token', (
            select value from public.whatsapp_shadow_settings where key = 'worker_token'
          )
        ),
        body := jsonb_build_object('source', 'supabase_cron')
      );
      $cron$
    );

    perform cron.schedule(
      'alameen-whatsapp-v2-shadow-worker',
      '* * * * *',
      $cron$
      select net.http_post(
        url := 'https://www.ameenfinance.co/api/internal/whatsapp-v2-shadow/worker',
        headers := jsonb_build_object(
          'Content-Type', 'application/json',
          'x-shadow-worker-token', (
            select value from public.whatsapp_shadow_settings where key = 'worker_token'
