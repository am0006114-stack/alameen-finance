create or replace function public.enqueue_whatsapp_v2_shadow_job(
  p_incoming_message_id text,
  p_wa_id text,
  p_customer_name text,
  p_customer_message text,
  p_message_type text,
  p_actual_reply text,
  p_initial_intent text,
  p_tracking_id text,
  p_application_id text,
  p_application_snapshot jsonb,
  p_conversation_snapshot jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id uuid;
begin
  if coalesce(trim(p_incoming_message_id), '') = '' then
    raise exception 'p_incoming_message_id is required';
  end if;
  if coalesce(trim(p_wa_id), '') = '' then
    raise exception 'p_wa_id is required';
  end if;

  insert into public.whatsapp_v2_shadow_jobs (
    incoming_message_id,
    wa_id,
    customer_name,
    customer_message,
    message_type,
    actual_reply,
    initial_intent,
    tracking_id,
    application_id,
    application_snapshot,
    conversation_snapshot,
    status,
    next_attempt_at
  )
  values (
    p_incoming_message_id,
    p_wa_id,
    p_customer_name,
    coalesce(p_customer_message, ''),
    coalesce(nullif(p_message_type, ''), 'text'),
    coalesce(p_actual_reply, ''),
    p_initial_intent,
    p_tracking_id,
    p_application_id,
    coalesce(p_application_snapshot, '{}'::jsonb),
    coalesce(p_conversation_snapshot, '{}'::jsonb),
    'queued',
    now()
  )
  on conflict (incoming_message_id) do nothing
  returning id into v_id;

  if v_id is null then
    select id into v_id
    from public.whatsapp_v2_shadow_jobs
    where incoming_message_id = p_incoming_message_id
    limit 1;
  end if;

  return v_id;
end;
$$;

