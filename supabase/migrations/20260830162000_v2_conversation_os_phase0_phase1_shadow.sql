create or replace function public.claim_whatsapp_v2_shadow_jobs(
  p_worker_id text,
  p_limit integer default 2
)
returns setof public.whatsapp_v2_shadow_jobs
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with selected as (
    select id
    from public.whatsapp_v2_shadow_jobs
    where status in ('queued','retry_wait')
      and coalesce(next_attempt_at, now()) <= now()
      and attempt_count < max_attempts
    order by created_at asc
    for update skip locked
    limit greatest(1, least(coalesce(p_limit, 2), 5))
  ), claimed as (
    update public.whatsapp_v2_shadow_jobs j
    set status = 'processing',
        attempt_count = j.attempt_count + 1,
        locked_at = now(),
        locked_by = p_worker_id,
        updated_at = now()
    from selected s
    where j.id = s.id
    returning j.*
  )
  select * from claimed;
end;
$$;

revoke all on function public.claim_whatsapp_v2_shadow_jobs(text, integer) from public, anon, authenticated;
grant execute on function public.claim_whatsapp_v2_shadow_jobs(text, integer) to service_role;

create or replace function public.requeue_stale_whatsapp_v2_shadow_jobs(
  p_stale_minutes integer default 10
)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  affected integer;
begin
  update public.whatsapp_v2_shadow_jobs
  set status = case when attempt_count >= max_attempts then 'dead_letter' else 'retry_wait' end,
      next_attempt_at = case when attempt_count >= max_attempts then null else now() end,
      last_error_code = coalesce(last_error_code, 'stale_worker_lock'),
      last_error_message = coalesce(last_error_message, 'V2 shadow worker lock expired and was released.'),
      locked_at = null,
      locked_by = null,
      completed_at = case when attempt_count >= max_attempts then now() else completed_at end,
      updated_at = now()
  where status = 'processing'
    and locked_at < now() - make_interval(mins => greatest(1, coalesce(p_stale_minutes, 10)));

  get diagnostics affected = row_count;
  return affected;
end;
$$;

revoke all on function public.requeue_stale_whatsapp_v2_shadow_jobs(integer) from public, anon, authenticated;
grant execute on function public.requeue_stale_whatsapp_v2_shadow_jobs(integer) to service_role;

-- Phase 0: async kick after queue inserts. This is the primary antidote to silent attempt_count=0 backlogs.
create or replace function public.kick_alameen_shadow_worker()
returns trigger
language plpgsql
security definer
set search_path = public, net
as $$
declare
  v_token text;
  v_url text;
begin
  select value into v_token
  from public.whatsapp_shadow_settings
  where key = 'worker_token';

  if coalesce(v_token, '') = '' then
    return new;
  end if;

  if tg_table_name = 'whatsapp_v2_shadow_jobs' then
    v_url := 'https://www.ameenfinance.co/api/internal/whatsapp-v2-shadow/worker';
  else
    v_url := 'https://www.ameenfinance.co/api/internal/whatsapp-shadow/worker';
  end if;

  begin
    perform net.http_post(
      url := v_url,
      headers := jsonb_build_object(
        'Content-Type', 'application/json',
        'x-shadow-worker-token', v_token
      ),
      body := jsonb_build_object(
        'source', 'queue_insert_trigger',
        'table', tg_table_name
      )
    );
  exception when others then
    -- Queue insertion must never fail because the async kicker failed.
    raise warning 'Shadow worker kick failed for %: %', tg_table_name, sqlerrm;
  end;

  return new;
end;
$$;

