const fs=require('fs'),path=require('path');
const root=process.argv[2]||process.cwd();
const base=path.join(root,'app','api','whatsapp','webhook','_lib','v3-os');
const req=['modelInterpreter.ts','stateStore.ts','judge.ts','costGuard.ts','safeFallback.ts','archiveSequenceLab.ts','runtimeShadow.ts','provider.ts'];
for(const f of req) if(!fs.existsSync(path.join(base,f))) throw new Error(`missing ${f}`);
const all=req.map(f=>fs.readFileSync(path.join(base,f),'utf8')).join('\n');
if(/whatsapp_v2_human_action_queue|AUTO_REPLY_IGNORED|pauseAutoReplyAfterSend/.test(all)) throw new Error('human dependency regression');
const runtime=fs.readFileSync(path.join(base,'runtimeShadow.ts'),'utf8');
if(!runtime.includes('allowMutation: false')) throw new Error('shadow mutation must remain disabled');
if(!runtime.includes('Fail closed')) throw new Error('fail-closed final verification missing');
if(!runtime.includes('interpretTurnWithAi')) throw new Error('AI interpreter not wired');
const archive=fs.readFileSync(path.join(base,'archiveSequenceLab.ts'),'utf8');
if(!archive.includes('whatsapp_v2_archive_cases')) throw new Error('archive sequence source missing');
if(archive.includes('allowMutation: true')) throw new Error('archive must not mutate business state');
const sql=fs.readFileSync(path.join(root,'supabase','migrations','20260901173500_v3_phase3_intelligence_sequence_lab.sql'),'utf8');
if(/\b(?:update|delete\s+from|insert\s+into)\s+public\.(applications|payments|refunds|application_state_audit)\b/i.test(sql)) throw new Error('business table mutation detected in V3 lab SQL');
if(/\bcron\.schedule\b|create\s+trigger/i.test(sql)) throw new Error('automatic cron/trigger detected');
if(!sql.includes("('lab_enabled','false')")) throw new Error('lab must default OFF');
console.log('V3 PHASE 3 SELFTEST PASS');
console.log('AI interpreter + persistent state + sequence judge present.');
console.log('Archive lab remains manual, cost-guarded, no business mutation.');
console.log('No human queue / no AI pause dependency.');
